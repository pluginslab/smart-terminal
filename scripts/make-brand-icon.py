#!/usr/bin/env python3
"""Smart Terminal's app icon, in the Agent and Intelligence line (Mobile Agent's recipe):
a Streamline Material Rounded Fill glyph in #5FB8C9 on the #0F181C canvas, filling 72%
of the tile, with the sparkle from "Ai Spark Prompt Fill" cut into the glyph's corner.

  scripts/make-brand-icon.py [layout-window-left-sidebar-fill|tab-group-fill] > Resources/AppIcon.svg
  scripts/render-icon.sh       # then AppIcon.png and AppIcon.icns

Glyphs: Resources/icon-src/*.svg (Streamline, licensed to hi@pluginslab.com). They and the
SVG made from them stay out of git (the repo is public); only the rendered AppIcon.png,
AppIcon-art.png and AppIcon.icns are committed. Get the three glyphs again with a
signed-in Streamline MCP: ico_7b6bKQY4QWW5K1Yv, ico_y8xds3DkHTrSCJnT, ico_KVIrSmsZdHwK52ye.
"""
import re, sys
base = sys.argv[1] if len(sys.argv) > 1 else "layout-window-left-sidebar-fill"
src = lambda n: re.search(r' d="([^"]+)"', open(f"Resources/icon-src/{n}.svg").read()).group(1)
glyph = src(base)
prompt = src("ai-spark-prompt-fill")
spark = prompt[prompt.index("M789.3333333333333 42.666666666666664"):]  # the sparkle's own subpath

CANVAS, GLYPH, FG = "#0F181C", "#5FB8C9", 0.72
# In glyph units (1024): the window sits where Agent's does (bottom left), the sparkle
# keeps its place top right. The window glyph spans 128..896; scaled to 680 wide.
s = 680 / 768
win = f'translate({85 - 128 * s:.3f} {258 - 128 * s:.3f}) scale({s:.5f})'
GAP = 44  # the notch: the sparkle grown by this much is cut out of the window
# Group bbox: x 85..981, y 42..938 (896); fit 72% of the tile, centred.
k = 1024 * FG / 896
ox, oy = (1024 - 896 * k) / 2 - 85 * k, (1024 - 896 * k) / 2 - 42 * k
print(f'''<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Smart Terminal app icon. Generated by scripts/make-brand-icon.py ({base}); full-bleed
       square, macOS applies its own mask. Render: scripts/render-icon.sh -->
  <defs>
    <mask id="notch" maskUnits="userSpaceOnUse" x="0" y="0" width="1024" height="1024">
      <rect width="1024" height="1024" fill="#fff"/>
      <path d="{spark}" fill="#000" stroke="#000" stroke-width="{2 * GAP}" stroke-linejoin="round"/>
    </mask>
  </defs>
  <rect width="1024" height="1024" fill="{CANVAS}"/>
  <g transform="translate({ox:.3f} {oy:.3f}) scale({k:.5f})" fill="{GLYPH}">
    <g mask="url(#notch)"><path transform="{win}" d="{glyph}"/></g>
    <path d="{spark}"/>
  </g>
</svg>''')
